"""How a generated output lives inside a file.

Each handler knows how to pull "our part" out of a file's current bytes and
how to write a new part back while keeping everything else intact:

* WholeFile  - we own the whole file (CLAUDE.md, .cursor/mcp.json, skills).
* JsonKey    - we own one top-level key of a shared JSON file
               (.gemini/settings.json -> mcpServers, opencode.json -> mcp).
* TomlBlock  - we own a marked block inside a TOML file (.codex/config.toml).

Parts are bytes for WholeFile and text for the others.
"""

import json
import re

MARKER = "Generated by samerules"


class MergeError(Exception):
    """The existing file can't be safely merged into (e.g. invalid JSON)."""


class WholeFile:
    kind = "file"

    def extract(self, current):
        return current

    def render(self, current, part):
        return part  # None means: delete the file

    def has_marker(self, part):
        try:
            return MARKER.encode() in part[:4096]
        except TypeError:
            return False


def _canon(value):
    return json.dumps(value, indent=2, sort_keys=False, ensure_ascii=False)


class JsonKey:
    kind = "json-key"

    def __init__(self, key, base=None):
        self.key = key
        self.base = base or {}

    def _load(self, current):
        if current is None:
            return None
        text = current.decode("utf-8") if isinstance(current, bytes) else current
        if not text.strip():
            return {}
        try:
            data = json.loads(text)
        except ValueError as e:
            raise MergeError("not plain JSON (%s); comments/JSONC can't be merged safely" % e)
        if not isinstance(data, dict):
            raise MergeError("top level is not a JSON object")
        return data

    def extract(self, current):
        data = self._load(current)
        if data is None or self.key not in data:
            return None
        return _canon(data[self.key])

    def render(self, current, part):
        data = self._load(current)
        if data is None:
            data = dict(self.base)
        if part is None:
            data.pop(self.key, None)
            leftover = {k: v for k, v in data.items() if k not in self.base or self.base[k] != v}
            if not leftover:
                return None
        else:
            data[self.key] = json.loads(part)
        return (json.dumps(data, indent=2, ensure_ascii=False) + "\n").encode("utf-8")

    def has_marker(self, part):
        return False


TOML_BEGIN = "# >>> samerules: MCP servers generated from .agents/mcp.json (edit the source, then run `samerules sync`) >>>"
TOML_END = "# <<< samerules <<<"
_BEGIN_RE = re.compile(r"^# >>> samerules\b.*$", re.M)
_END_RE = re.compile(r"^# <<< samerules <<<[ \t]*$", re.M)
_TABLE_RE = re.compile(r"^\s*\[\s*mcp_servers\s*\.\s*(\"[^\"]+\"|'[^']+'|[A-Za-z0-9_-]+)\s*\]", re.M)


class TomlBlock:
    kind = "toml-block"

    def __init__(self, names=()):
        self.names = set(names)  # server names we generate, for duplicate detection
        self.force = False  # with --force, hand-written tables for those names are replaced

    def _drop_tables(self, text):
        out, skipping = [], False
        for line in text.splitlines(True):
            st = line.strip()
            if st.startswith("["):
                m = re.match(r"^\[\s*mcp_servers\s*\.\s*(\"[^\"]+\"|'[^']+'|[A-Za-z0-9_-]+)\s*[.\]]", st)
                skipping = bool(m and m.group(1).strip("\"'") in self.names)
            if not skipping:
                out.append(line)
        return "".join(out)

    @staticmethod
    def _text(current):
        return current.decode("utf-8") if isinstance(current, bytes) else current

    def _span(self, text):
        b = _BEGIN_RE.search(text)
        if not b:
            return None
        e = _END_RE.search(text, b.end())
        if not e:
            raise MergeError("found a samerules start marker but no end marker")
        end = e.end()
        if text[end:end + 1] == "\n":
            end += 1
        return b.start(), end

    def extract(self, current):
        if current is None:
            return None
        text = self._text(current)
        span = self._span(text)
        if not span:
            return None
        return text[span[0]:span[1]]

    def outside(self, current):
        text = self._text(current) if current is not None else ""
        span = self._span(text)
        if span:
            return text[:span[0]] + text[span[1]:]
        return text

    def render(self, current, part):
        text = self._text(current) if current is not None else ""
        rest = self.outside(current)
        dupes = sorted(n for n in (m.group(1).strip("\"'") for m in _TABLE_RE.finditer(rest)) if n in self.names)
        if part is not None and dupes:
            if not self.force:
                raise MergeError("already defines [mcp_servers.%s] by hand; use --force to replace it "
                                 "with the .agents/mcp.json version" % dupes[0])
            text = self._drop_tables(text)
        span = self._span(text)
        if span:
            new = text[:span[0]] + (part or "") + text[span[1]:]
            if part is None:
                new = re.sub(r"\n{3,}", "\n\n", new)
        elif part is None:
            new = text
        else:
            new = text
            if new and not new.endswith("\n"):
                new += "\n"
            if new.strip():
                new += "\n"
            new += part
        if not new.strip():
            return None
        return new.encode("utf-8")

    def has_marker(self, part):
        return True
