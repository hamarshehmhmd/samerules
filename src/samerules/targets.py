"""Render the canonical source into every harness's native files."""

import json
import os
from dataclasses import dataclass, field
from typing import List

from . import frontmatter, mcp
from .handlers import JsonKey, TomlBlock, WholeFile

HEADER = ("<!-- Generated by samerules from .agents/ - do not edit by hand. "
          "Change the source and run `samerules sync`. -->")

# what each target writes, for `samerules targets` and the README
TARGET_FILES = {
    "agents": ["AGENTS.md"],
    "claude": ["CLAUDE.md", ".claude/rules/<rule>.md", ".claude/skills/<skill>/", ".mcp.json"],
    "cursor": [".cursor/rules/<rule>.mdc", ".cursor/mcp.json"],
    "codex": ["AGENTS.md", ".codex/config.toml [mcp_servers]"],
    "gemini": ["GEMINI.md", ".gemini/settings.json (mcpServers key)"],
    "opencode": ["AGENTS.md", "opencode.json (mcp key)"],
    "copilot": [".github/copilot-instructions.md", ".github/instructions/<rule>.instructions.md",
                ".github/skills/<skill>/", ".vscode/mcp.json"],
    "windsurf": [".windsurf/rules/<rule>.md", ".devin/mcp_config.json"],
}
# who reads .agents/skills natively (no copy needed)
NATIVE_SKILLS = {"agents", "codex", "cursor", "gemini", "opencode", "windsurf"}
AGENTS_MD_WRITERS = {"agents", "codex", "opencode"}


@dataclass
class Output:
    path: str  # posix, relative to root
    handler: object
    part: object  # bytes for WholeFile, str otherwise
    targets: List[str] = field(default_factory=list)
    mode: int = 0o644


def _section(rule):
    body = rule.body_without_title()
    if rule.apply == "glob":
        head = "## %s\n\n_Applies to files matching: %s_" % (
            rule.title, ", ".join("`%s`" % g for g in rule.globs))
    elif rule.apply == "auto":
        head = "## %s\n\n_Use when relevant: %s_" % (rule.title, rule.description or "see below")
    else:
        return rule.body.strip("\n")
    return head + ("\n\n" + body if body else "")


def instructions(rules, include=("always", "glob", "auto")):
    chunks = [HEADER]
    always = [r for r in rules if r.apply == "always" and "always" in include]
    other = [r for r in rules if r.apply != "always" and r.apply in include]
    for r in always + other:
        chunks.append(_section(r))
    return "\n\n".join(chunks).rstrip("\n") + "\n"


def _fm(pairs):
    lines = ["---"]
    for k, v in pairs:
        if isinstance(v, bool):
            lines.append("%s: %s" % (k, "true" if v else "false"))
        elif isinstance(v, list):
            lines.append("%s:" % k)
            lines.extend("  - %s" % frontmatter.quote(x) for x in v)
        elif v is None:
            continue
        else:
            lines.append("%s: %s" % (k, v))
    lines.append("---")
    return "\n".join(lines)


def _with_fm(pairs, rule):
    return _fm(pairs) + "\n" + HEADER + "\n\n" + rule.body.strip("\n") + "\n"


def cursor_rule(rule):
    pairs = []
    if rule.apply == "auto" or (rule.description and rule.apply != "manual"):
        pairs.append(("description", frontmatter.quote(rule.description) if rule.description else None))
    if rule.apply == "glob":
        pairs.append(("globs", ",".join(rule.globs)))
    pairs.append(("alwaysApply", rule.apply == "always"))
    return _with_fm(pairs, rule)


def windsurf_rule(rule):
    trig = {"always": "always_on", "glob": "glob", "auto": "model_decision", "manual": "manual"}[rule.apply]
    pairs = [("trigger", trig)]
    if rule.apply == "glob":
        pairs.append(("globs", ",".join(rule.globs)))
    if rule.description:
        pairs.append(("description", frontmatter.quote(rule.description)))
    return _with_fm(pairs, rule)


def claude_rule(rule):
    return _with_fm([("paths", rule.globs)], rule)


def copilot_rule(rule):
    pairs = [("applyTo", frontmatter.quote(",".join(rule.globs)) if rule.globs else '"**"')]
    if rule.description:
        pairs.append(("description", frontmatter.quote(rule.description)))
    return _with_fm(pairs, rule)


def _json_bytes(obj):
    return (json.dumps(obj, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def render(src):
    """Return ``(outputs, warnings)`` for every enabled target."""
    warnings = []
    outs = {}

    def add(path, handler, part, target, mode=0o644):
        if part is None:
            return
        if isinstance(handler, WholeFile) and isinstance(part, str):
            part = part.encode("utf-8")
        if path in outs:
            if target not in outs[path].targets:
                outs[path].targets.append(target)
            return
        outs[path] = Output(path, handler, part, [target], mode)

    targets = src.targets
    agents_md = any(t in AGENTS_MD_WRITERS for t in targets)

    def rules_for(t):
        return [r for r in src.rules if r.for_target(t)]

    for t in targets:
        rules = rules_for(t)
        if t in AGENTS_MD_WRITERS:
            md_rules = [r for r in src.rules if r.targets is None or set(r.targets) & AGENTS_MD_WRITERS]
            if md_rules:
                add("AGENTS.md", WholeFile(), instructions(md_rules), t)
        elif t == "claude":
            if rules:
                add("CLAUDE.md", WholeFile(), instructions(rules, include=("always", "auto")), t)
            for r in rules:
                if r.apply == "glob":
                    add(".claude/rules/%s.md" % r.name, WholeFile(), claude_rule(r), t)
        elif t == "gemini" and rules:
            add("GEMINI.md", WholeFile(), instructions(rules), t)
        elif t == "copilot":
            if rules:
                add(".github/copilot-instructions.md", WholeFile(), instructions(rules, include=("always", "auto")), t)
            for r in rules:
                if r.apply == "glob":
                    add(".github/instructions/%s.instructions.md" % r.name, WholeFile(), copilot_rule(r), t)
        elif t == "cursor":
            for r in rules:
                if r.apply == "always" and agents_md:
                    continue  # Cursor already reads AGENTS.md; don't load it twice
                add(".cursor/rules/%s.mdc" % r.name, WholeFile(), cursor_rule(r), t)
        elif t == "windsurf":
            for r in rules:
                if r.apply == "always" and agents_md:
                    continue  # Windsurf / Devin already read AGENTS.md
                add(".windsurf/rules/%s.md" % r.name, WholeFile(), windsurf_rule(r), t)

        # skills: only harnesses that don't read .agents/skills get a copy
        mirror = {"claude": ".claude/skills", "copilot": ".github/skills"}.get(t)
        if mirror:
            for sk in src.skills:
                for rel in sk.files:
                    p = os.path.join(sk.path, *rel.split("/"))
                    with open(p, "rb") as fh:
                        data = fh.read()
                    mode = 0o755 if os.access(p, os.X_OK) else 0o644
                    add("%s/%s/%s" % (mirror, sk.name, rel), WholeFile(), data, t, mode)

        # MCP servers
        if t in ("claude", "cursor", "windsurf", "copilot"):
            servers = mcp.json_servers(t, src.mcp, warnings)
            if servers:
                path = {"claude": ".mcp.json", "cursor": ".cursor/mcp.json",
                        "windsurf": ".devin/mcp_config.json", "copilot": ".vscode/mcp.json"}[t]
                key = "servers" if t == "copilot" else "mcpServers"
                add(path, WholeFile(), _json_bytes({key: servers}), t)
        elif t == "gemini":
            servers = mcp.json_servers(t, src.mcp, warnings)
            if servers:
                add(".gemini/settings.json", JsonKey("mcpServers"), json.dumps(servers, indent=2, ensure_ascii=False), t)
        elif t == "opencode":
            servers = mcp.json_servers(t, src.mcp, warnings)
            if servers:
                add("opencode.json", JsonKey("mcp", {"$schema": "https://opencode.ai/config.json"}),
                    json.dumps(servers, indent=2, ensure_ascii=False), t)
        elif t == "codex":
            block = mcp.codex_block(src.mcp, warnings)
            if block:
                add(".codex/config.toml", TomlBlock(mcp.servers_for("codex", src.mcp)), block, t)
    return list(outs.values()), warnings


def handler_for(path):
    """Handler used to clean up a previously generated path no longer produced."""
    if path == ".gemini/settings.json":
        return JsonKey("mcpServers")
    if path == "opencode.json":
        return JsonKey("mcp", {"$schema": "https://opencode.ai/config.json"})
    if path == ".codex/config.toml":
        return TomlBlock()
    return WholeFile()
