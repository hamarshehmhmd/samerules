import json
import os
import sys

import pytest
from helpers import exists, read, run, write

CLAUDE = "# Rules\n\n- Use pnpm.\n- Run `pnpm test` before committing.\n"


def messy_repo(repo):
    write(repo, "CLAUDE.md", CLAUDE)
    write(repo, "AGENTS.md", "# Rules\n\n- Use pnpm.\n")  # drifted copy
    write(repo, ".cursor/rules/api.mdc", "---\ndescription: API rules\nglobs: src/api/**\nalwaysApply: false\n---\n# API\n\n- zod everywhere\n")
    write(repo, ".cursor/rules/style.mdc", "---\nalwaysApply: true\n---\n" + CLAUDE)  # duplicate of main
    write(repo, ".cursor/rules/db.mdc", "---\ndescription: DB work\n---\n# DB\n")
    write(repo, ".cursor/rules/rel.mdc", "---\n---\nmanual one\n")
    write(repo, ".windsurf/rules/ws.md", "---\ntrigger: model_decision\ndescription: ws desc\n---\nws body\n")
    write(repo, ".github/instructions/py.instructions.md", "---\napplyTo: \"**/*.py\"\n---\nuse ruff\n")
    write(repo, ".github/instructions/all.instructions.md", "---\napplyTo: \"**\"\n---\neverything\n")
    write(repo, ".claude/rules/tests.md", "---\npaths:\n  - tests/**\n---\npytest only\n")
    write(repo, ".claude/skills/deploy/SKILL.md", "---\nname: deploy\ndescription: Deploy\n---\nsteps\n")
    write(repo, ".claude/skills/notaskill/README.md", "x")
    write(repo, ".github/skills/Bad_Skill/SKILL.md", "---\nname: Bad_Skill\ndescription: d\n---\n")
    write(repo, ".mcp.json", json.dumps({"mcpServers": {"pg": {"type": "stdio", "command": "npx", "args": ["pg"], "env": {"U": "${U}"}}}}))
    write(repo, ".cursor/mcp.json", json.dumps({"mcpServers": {"pg": {"command": "npx", "args": ["pg"], "env": {"U": "${env:U}"}},
                                                                "gh": {"url": "https://gh"}}}))
    write(repo, ".vscode/mcp.json", json.dumps({"servers": {"pg": {"type": "stdio", "command": "bunx", "args": ["pg"]}}}))
    write(repo, "opencode.json", json.dumps({"mcp": {"oc": {"type": "local", "command": ["oc", "--x"]}, "bad": {"type": "local"}}}))
    write(repo, ".gemini/settings.json", "{not json")
    write(repo, ".codex/config.toml", '[mcp_servers.cx]\ncommand = "cx"\nenv_vars = ["T"]\n')


def test_import_messy_repo(repo):
    messy_repo(repo)
    code, out, _ = run(repo, "import")
    assert code == 0, out
    assert read(repo, ".agents/rules/main.md") == CLAUDE
    assert "rules/main.md      <- CLAUDE.md" in out
    assert "NOTE AGENTS.md differs from CLAUDE.md" in out
    api = read(repo, ".agents/rules/api.md")
    assert "description: API rules" in api and "apply: glob" in api and "src/api/**" in api
    assert not exists(repo, ".agents/rules/style.md") or "pnpm" in read(repo, ".agents/rules/style.md")
    assert "apply: auto" in read(repo, ".agents/rules/db.md")
    assert "apply: manual" in read(repo, ".agents/rules/rel.md")
    assert "apply: auto" in read(repo, ".agents/rules/ws.md")
    assert "**/*.py" in read(repo, ".agents/rules/py.md")
    assert read(repo, ".agents/rules/all.md") == "everything\n"
    assert "tests/**" in read(repo, ".agents/rules/tests.md")
    assert exists(repo, ".agents/skills/deploy/SKILL.md")
    assert not exists(repo, ".agents/skills/notaskill")
    assert "invalid name" in out
    servers = json.loads(read(repo, ".agents/mcp.json"))["mcpServers"]
    assert servers["pg"] == {"command": "npx", "args": ["pg"], "env": {"U": "${U}"}}
    assert servers["gh"] == {"url": "https://gh"}
    assert servers["oc"] == {"command": "oc", "args": ["--x"]}
    assert "pg' in .vscode/mcp.json differs" in out
    assert "skipped .gemini/settings.json: not plain JSON" in out
    assert "unrecognised shape" in out
    if sys.version_info >= (3, 11):
        assert servers["cx"] == {"command": "cx", "env": {"T": "${T}"}}
    else:
        assert "needs Python 3.11" in out
    targets = json.loads(read(repo, ".agents/samerules.json"))["targets"]
    assert targets == ["agents", "claude", "cursor", "codex", "gemini", "opencode", "copilot", "windsurf"]


def test_import_then_sync_force_then_check(repo):
    messy_repo(repo)
    run(repo, "import")
    os.remove(os.path.join(str(repo), ".agents/skills/Bad_Skill/SKILL.md"))
    os.rmdir(os.path.join(str(repo), ".agents/skills/Bad_Skill"))
    write(repo, ".gemini/settings.json", "{}")
    code, out, _ = run(repo, "sync")
    assert code == 1 and "hand-written" in out
    code, out, _ = run(repo, "sync", "--force")
    assert code == 0, out
    code, out, _ = run(repo, "check")
    assert code == 0, out


def test_import_refuses_twice(repo):
    write(repo, "AGENTS.md", "x\n")
    assert run(repo, "import")[0] == 0
    code, _, err = run(repo, "import")
    assert code == 2 and "--force" in err
    assert run(repo, "import", "--force")[0] == 0


def test_import_strips_our_header_and_at_import(repo):
    write(repo, "AGENTS.md", "<!-- Generated by samerules from .agents/ - x -->\n\nreal\n")
    write(repo, "CLAUDE.md", "@AGENTS.md\n")
    code, out, _ = run(repo, "import")
    assert read(repo, ".agents/rules/main.md") == "real\n"
    assert "just imports AGENTS.md" in out


