def test_import_name_clash(repo):
    write(repo, ".cursor/rules/api.mdc", "---\nglobs: a\n---\none\n")
    write(repo, ".claude/rules/api.md", "---\npaths: b\n---\ntwo\n")
    code, out, _ = run(repo, "import")
    assert "a different rule named 'api'" in out
    assert "one" in read(repo, ".agents/rules/api.md")


